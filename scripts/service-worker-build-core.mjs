// Service-worker / integrity-policy build core — PURE logic, NO Node imports.
// Single source of truth shared by:
//   - scripts/build-service-worker.mjs                        (real I/O over dist/)
//   - packages/engine/tests/service_worker_build_core.test.ts (synthetic unit tests)
// Same split as guardrails-core.mjs / publication-gate-core.mjs: keeping this
// file dependency-free lets the TypeScript test import it (tsconfig allowJs)
// without pulling Node globals in.
//
// The whole point of computing this at build time is BUNDLE-01's cache
// invalidation rule: the id below is derived from the sha256 of every built
// file, so any change to the shipped app produces a different id, a different
// cache name and a different service-worker script — never a stale shell after
// an update. Nothing here reads a clock, a git sha or an environment variable:
// the same dist/ always produces the same policy, byte for byte.

export const APP_INTEGRITY_POLICY_VERSION = "app-integrity-v1";
export const APP_INTEGRITY_POLICY_URL = "/app-integrity.json";
export const SERVICE_WORKER_FILENAME = "sw.js";

/** Files that are generated BY this step and must never be inputs to it. */
export const GENERATED_FILENAMES = new Set([SERVICE_WORKER_FILENAME, "app-integrity.json"]);

/** Data payloads live here; everything else built is app shell. */
export const DATA_DIR_PREFIX = "/data/";
const MANIFEST_SUFFIX = ".manifest.json";

/** `dist/assets/index-abc.js` -> `/assets/index-abc.js` (POSIX separators, always). */
export function distPathToUrl(relativePath) {
  return "/" + relativePath.split("\\").join("/").replace(/^\/+/, "");
}

/** True for a built file this step must ignore (it produces it). */
export function isGeneratedArtifact(relativePath) {
  const url = distPathToUrl(relativePath);
  return GENERATED_FILENAMES.has(url.slice(1));
}

/** A data payload (`/data/x.json`) that is not itself a manifest. */
export function isDataAssetUrl(url) {
  return url.startsWith(DATA_DIR_PREFIX) && url.endsWith(".json") && !url.endsWith(MANIFEST_SUFFIX);
}

/** The manifest URL a data asset would carry: `/data/x.json` -> `/data/x.manifest.json`. */
export function manifestUrlFor(assetUrl) {
  return assetUrl.slice(0, -".json".length) + MANIFEST_SUFFIX;
}

/**
 * Build id: sha256 over the canonical `url:sha256` lines of every built file,
 * sorted. `hashHex` is injected so this stays free of `node:crypto` — the CLI
 * passes the real one, the test passes a deterministic fake.
 */
export function computeBuildId(fileEntries, hashHex) {
  const canonical = [...fileEntries]
    .map((entry) => `${entry.url}:${entry.sha256}`)
    .sort()
    .join("\n");
  return hashHex(canonical);
}

/**
 * Assembles the policy from the hashed dist listing.
 *
 * `files`: `[{ url, sha256, bytes }]` for every non-generated built file.
 * `existingManifestUrls`: the manifest URLs actually present in the build —
 * presence here is what flips `manifestRequired` to true, which is how a
 * packaged bundle's missing manifest becomes a fail-closed condition at runtime
 * while today's manifest-less proxy asset keeps loading exactly as before.
 */
export function buildIntegrityPolicy(files, existingManifestUrls, hashHex) {
  const sorted = [...files].sort((a, b) => (a.url < b.url ? -1 : a.url > b.url ? 1 : 0));
  const dataAssets = sorted.filter((file) => isDataAssetUrl(file.url));
  const manifestSet = new Set(existingManifestUrls);

  const data = dataAssets.map((file) => {
    const manifestUrl = manifestUrlFor(file.url);
    return { url: file.url, manifestUrl, manifestRequired: manifestSet.has(manifestUrl) };
  });

  // Every built file is precached — shell, data payloads and their manifests
  // alike. A cold start with no network has to find the listone in the cache,
  // not just the HTML: an app that boots offline into an empty listone would
  // not be an auction tool.
  const precache = ["/", ...sorted.map((file) => file.url), APP_INTEGRITY_POLICY_URL];
  const uniquePrecache = [...new Set(precache)];

  const fileEntries = sorted.map((file) => ({ url: file.url, sha256: file.sha256, bytes: file.bytes }));

  return {
    policy_version: APP_INTEGRITY_POLICY_VERSION,
    build_id: computeBuildId(fileEntries, hashHex),
    files: fileEntries,
    data,
    precache: uniquePrecache,
  };
}

/** Canonical 2-space JSON with a trailing newline — same serialization rule the
 *  listone candidate/bundle contract uses, so the file is diffable and stable. */
export function serializePolicy(policy) {
  return JSON.stringify(policy, null, 2) + "\n";
}
