// Local git-hooks core — PURE logic, NO Node imports (string-only).
// Single source of truth shared by:
//   - scripts/graphify-bootstrap.mjs             (writes the hook into .git/hooks/)
//   - packages/engine/tests/pre_push_hook.test.ts (unit tests + real `sh` execution)
// Same split as guardrails-core.mjs / secret-scan-core.mjs, and for the same
// reason: the TypeScript test imports it (tsconfig allowJs) without pulling
// Node globals.
//
// Why this exists (DOC-01 Fase 2, issue #258): `main` and `production` have no
// branch protection — GitHub Free on a private repo does not offer it, and Owner
// has closed the "no paid plan, ever" decision. The prohibition on pushing
// directly to them is therefore a rule of governance (docs/NO_GO.md §merge)
// with nothing mechanical behind it. This hook is the cheap mechanical half:
// it does not make the violation impossible, it makes the realistic accident —
// a session pushing to the branch it happens to be on — stop before it leaves
// the machine. The post-hoc alarm (.github/workflows/push-audit.yml) covers
// what gets through.

// The two branches that may only ever receive commits through a merged PR.
// `production` is stricter still: any push to it IS a Production deploy
// (docs/NO_GO.md §merge), always fascia C, never the Executive's to perform.
export const PROTECTED_BRANCHES = ["main", "production"];

// Version marker. The installer rewrites a hook that carries this marker
// (idempotent upgrade) and refuses to touch one that does not (a hook written
// by a human or another tool is never clobbered).
export const PRE_PUSH_MARKER = "fantacalcio-pre-push-guard";
export const PRE_PUSH_VERSION = 1;

/**
 * The pre-push hook, as a self-contained POSIX sh script.
 *
 * Deliberately depends on nothing but /bin/sh: not on node, not on this
 * checkout's scripts/, not on anything installed. A guard that stops working
 * because a file in the repo moved is not a guard.
 */
export function renderPrePushHook() {
  const cases = PROTECTED_BRANCHES.map((b) => `refs/heads/${b}`).join("|");
  return `#!/bin/sh
# ${PRE_PUSH_MARKER} v${PRE_PUSH_VERSION} — generated by scripts/git-hooks-core.mjs,
# installed by \`npm run graphify:bootstrap\`. Do not edit by hand: the bootstrap
# rewrites any file carrying the marker above.
#
# Rifiuta i push diretti su ${PROTECTED_BRANCHES.join(" e ")}.
# Fonte normativa: docs/NO_GO.md §merge — si passa sempre da una PR
# (branch -> Draft PR -> CI -> review -> merge). Un push su production e' per
# di piu' un deploy Production, sempre fascia C.
#
# Nessun flag di bypass, per scelta: l'unico modo di non applicarlo e'
# rimuovere consapevolmente questo file da .git/hooks/. (\`git push --no-verify\`
# salta ogni hook: e' un builtin di git che nessun hook puo' disabilitare, ed e'
# comunque un atto esplicito, non un incidente.)
#
# stdin: una riga per ref pushata — "<local ref> <local sha> <remote ref> <remote sha>".
# Si guarda il REMOTE ref: e' quello che dice su quale branch del remoto
# finiranno i commit, indipendentemente da come si chiama il branch locale.

blocked=''
while read -r _local_ref _local_sha remote_ref _remote_sha; do
  case "$remote_ref" in
    ${cases})
      blocked="$blocked $remote_ref"
      ;;
  esac
done

if [ -n "$blocked" ]; then
  echo "" >&2
  echo "pre-push BLOCCATO — push diretto su:$blocked" >&2
  echo "Si passa sempre da una PR. Fonte normativa: docs/NO_GO.md §merge." >&2
  echo "" >&2
  exit 1
fi

exit 0
`;
}

/**
 * Install decision for <hooks dir>/pre-push.
 *
 * @param {string|null} existing  current file content, or null when absent
 * @returns {"install"|"update"|"skip-foreign"|"unchanged"}
 */
export function prePushInstallAction(existing) {
  if (existing === null || existing === "") return "install";
  if (!existing.includes(PRE_PUSH_MARKER)) return "skip-foreign";
  return existing === renderPrePushHook() ? "unchanged" : "update";
}
